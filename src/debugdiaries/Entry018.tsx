export const E18_FX_WINDOWS: [number, number][] = [[CUTS[1], 22]]; // frames 178–199, spliced via ffmpeg trim+concat
export const DebugDiaries018: React.FC<{shaders?: boolean}> = ({shaders = false}) => {
  const trLen = (i: number) => (i === 0 ? 22 : TR);
  const durs = COMPS.map((_, i) => (i + 1 < CUTS.length ? CUTS[i + 1] - CUTS[i] + trLen(i) : E18_TOTAL - CUTS[i]));
  const pres = [
    shaders ? filmBurn({seed: 3}) : fade(),
    glitch(),
    clockWipe({width: 1080, height: 1920}),
    slide({direction: "from-bottom"}),
    fade(), // ripple dropped: in full renders it lost the outgoing scene
  ];
  return (
    <AbsoluteFill style={{background: "#121316", color: C.text}}>
      <TransitionSeries>
        {COMPS.map((Comp, i) => (
          <React.Fragment key={i}>
            <TransitionSeries.Sequence durationInFrames={durs[i]}>
              <Comp off={CUTS[i]} />
            </TransitionSeries.Sequence>
            {i + 1 < COMPS.length ? (
              <TransitionSeries.Transition presentation={pres[i] as never} timing={i === 3 ? springTiming({config: {damping: 200}, durationInFrames: TR}) : linearTiming({durationInFrames: i === 0 ? 22 : TR})} />
            ) : null}
          </React.Fragment>
        ))}
      </TransitionSeries>
      <Checklist />
      <AbsoluteFill style={{zIndex: 20}}><Hud ep="018" total={E18_TOTAL} /></AbsoluteFill>
      <AbsoluteFill style={{zIndex: 30, pointerEvents: "none"}}><Grain /></AbsoluteFill>
    </AbsoluteFill>
  );
};
